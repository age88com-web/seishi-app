// src/lib/qimenPurpose/kakuAliases.ts
//
// 役割:
//   用途データベース（qimenMeaning/purposeMeaning.ts）の格局表記のうち、
//   検索時だけ実際の格局名（jikaku.ts の match.name）へ展開するための
//   エイリアス表と展開関数。
//
// 重要な方針:
//   ・資料側のデータ（qimenMeaning/purposeMeaning.ts）は一切書き換えない。
//     「日奇得使」「龍虎風雲遁」「四乙（龍虎風雲）遁」は資料の表記のまま
//     保持し、この展開関数を呼んだときだけ複数の格局名へ展開される。
//   ・「升」「昇」の表記ゆれ（丙奇昇殿→丙奇升殿、丁奇昇殿→丁奇升殿）も
//     ここで吸収する。
//   ・展開ルールはユーザー指示にある3種類のみ。それ以外の名称は
//     そのまま1件の配列として返す（推測で追加しない）。
//   ・検索エンジン（src/lib/qimenSearch/）へは今回組み込まない。用途評価
//     レイヤーの中に関数を用意するだけで、呼び出し元は無い。
//
// 展開ルールの出典:
//   ・「日奇得使」→ 乙奇得使／丙奇得使／丁奇得使: ユーザー指示による。
//   ・「龍虎風雲遁」「四乙（龍虎風雲）遁」→ 龍遁／虎遁／風遁／雲遁:
//     ユーザー指示による（docs/source/奇門遁甲講義案N.pdf p.67 の
//     「四乙（龍虎風雲）遁」という表記が、天盤乙を使う4格＝龍遁・虎遁・
//     風遁・雲遁の総称であることの手がかりになっている）。
//   ・「丙奇昇殿」→「丙奇升殿」、「丁奇昇殿」→「丁奇升殿」:
//     jikaku.ts の表記（升）に合わせるだけの文字ゆれ吸収。

const KAKU_ALIASES: Record<string, string[]> = {
  日奇得使: ["乙奇得使", "丙奇得使", "丁奇得使"],
  龍虎風雲遁: ["龍遁", "虎遁", "風遁", "雲遁"],
  "四乙（龍虎風雲）遁": ["龍遁", "虎遁", "風遁", "雲遁"],
  丙奇昇殿: ["丙奇升殿"],
  丁奇昇殿: ["丁奇升殿"],
};

/**
 * 格局名（用途データベースの表記）を、検索で使える実際の格局名へ展開する。
 * エイリアス表に無い名称はそのまま1件の配列として返す（変更しない）。
 */
export function resolveKakuAlias(name: string): string[] {
  return KAKU_ALIASES[name] ?? [name];
}

/** 複数の格局名（エイリアス含む）をまとめて展開し、重複を除いた配列で返す。 */
export function resolveKakuAliases(names: string[]): string[] {
  return Array.from(new Set(names.flatMap(resolveKakuAlias)));
}
