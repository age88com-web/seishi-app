import type { ShinsatsuInput, ShinsatsuResult } from "../types";
import { resolveJianchu } from "../jianchu";

/**
 * 「日家凶神」第1グループ（小時＝月建・死神・死気＝定日・血支＝閉日）を
 * 判定する。吉神は今回対象外のため kichijin は常に空配列。
 * 判定ロジックの本体（十二建除のステータス判定）は jianchu.ts をそのまま
 * 呼び出すだけで、再実装しない。
 */
export function resolveKyoushinGroup1(input: ShinsatsuInput): ShinsatsuResult {
  const { monthBranch, dayBranch } = input;
  const jianchuName = resolveJianchu({ monthBranch, dayBranch }).name;

  const kyojin: string[] = [];
  if (jianchuName === "建") kyojin.push("小時");
  if (jianchuName === "平") kyojin.push("死神");
  if (jianchuName === "定") kyojin.push("死気");
  if (jianchuName === "閉") kyojin.push("血支");

  return { kichijin: [], kyojin };
}
