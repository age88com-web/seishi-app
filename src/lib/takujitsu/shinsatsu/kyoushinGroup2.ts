//     テキスト自身に根拠がある名称）。テキストの表本体の列見出し
//     「災殺」を採用し、「災煞」「天火」は検証用fixtureでのみ許容する。
//     「月殺」も同様に、実例PDFでは「月虚」（本文が明記する別名）
//     「月煞」（異体字）として頻出するため、表本体の列見出し「月殺」を
//     採用し、「月虚」「月煞」は検証用fixtureでのみ許容する。
//   ・月刑: 実例PDFで「月刑」がそのまま720/720完全一致するため、別名の
//     整理は不要。
//
// 月破の例外処理について（重要・本文だけでは意味が確定しないため保留）:
//   p.21の本文には「子・午月→災殺（子午日）／未・申月→月刑（丑寅日）／
//   卯・酉月→災殺（卯酉日）／上記の日は凶日とならない。」という記述が
//   ある。月破の対象日（月建の冲日）と、今回実装した劫殺・災殺・月殺・
//   月刑の該当日を突き合わせたところ、確かに
//     ・monthBranch が子・午・卯・酉のとき、月破の対象日＝その月の災殺日
//     ・monthBranch が未・申のとき、月破の対象日＝その月の月刑日
//   と完全に一致することを確認した（本文の記述と矛盾しない）。
//   しかし、この一致が「月破を凶日として扱わない」という意味かどうかを
//   擇日実例.pdfで検証したところ、該当するすべての行で「月破」と
//   「災殺」（または月刑）が同一行に共存して出現しており
//   （例：二月（monthBranch=卯）癸酉の凶神欄に「月破…災煞天火…」と
//   両方掲載）、単純な「月破の対象から除外する」という解釈は実例PDFの
//   実際の掲載と一致しない（除外ルールを適用すると690/720まで悪化する。
//   除外なしの単純な冲ルールのみで720/720完全一致する）。
//   本文の「上記の日は凶日とならない」が具体的に何を意味するのか
//   （月破という名称を使わないだけで別の名で凶日のままなのか、月破の
//   忌事項の一部だけが免除されるのか等）を、この文言だけでは確定でき
//   ないため、推測で補わずに「例外は実装しない（月破は常に単純な
//   monthBranchの冲＝dayBranchで判定する）」こととし、この文言自体は
