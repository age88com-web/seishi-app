// 名称の整理（実例PDFで確認済み。重複実装を避けるため1概念1名称とする）:
//   ・月破（大耗）: 実例PDFで「月破」「大耗」は720/720すべて同一行に
//     出現する完全な別名。テキストの主名「月破」を採用する。
//   ・劫殺・災殺・月殺: p.22の表本体の列見出しどおり3列（劫殺・災殺・月殺）
//     をそのまま3つの凶神として実装する（依頼の対象名にも一致）。
//     実例PDFでは「劫殺」はほぼ全件「劫煞」（殺の異体字「煞」）として
//     印字されているが、殺／煞は同一字の異体字であり別語ではないため、
//     テキストの表記「劫殺」を採用し、「劫煞」は検証用fixtureでのみ
//     異体字として許容する（未→末等の既存の文字化け許容と同じ扱い）。
//     「災殺」は実例PDFで「災煞」（同じく異体字）に加え、テキストp.22の
//     見出しにある別名「天火」としても頻出する（歳殺（天獄、天火）と
