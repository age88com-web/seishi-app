import type { ShinsatsuInput, ShinsatsuResult } from "../types";

/** ［区分A］月破（大耗）（p.21）。月建の冲（対冲）となる日辰。 */
const YUEPO: Record<string, string> = {
  子: "午", 午: "子", 丑: "未", 未: "丑", 寅: "申", 申: "寅",
  卯: "酉", 酉: "卯", 辰: "戌", 戌: "辰", 巳: "亥", 亥: "巳",
};

/** 三合の長生局グループ（寅午戌＝火局、亥卯未＝木局、申子辰＝水局、巳酉丑＝金局）。劫殺・災殺・月殺で使用。 */
const SANHE_TRIO_GROUPS: readonly (readonly string[])[] = [
  ["寅", "午", "戌"],
  ["亥", "卯", "未"],
  ["申", "子", "辰"],
  ["巳", "酉", "丑"],
];
function trioIndexOf(monthBranch: string): number {
  return SANHE_TRIO_GROUPS.findIndex((g) => g.includes(monthBranch));
}

/** ［区分A］劫殺（p.22）。三合局ごとに固定の1地支（表の第1列）。 */
const JIESHA_BY_TRIO: readonly string[] = ["亥", "申", "巳", "寅"];
/** ［区分A］災殺（p.22）。三合局ごとに固定の1地支（表の第2列）。 */
const ZAISHA_BY_TRIO: readonly string[] = ["子", "酉", "午", "卯"];
/** ［区分A］月殺（p.22）。三合局ごとに固定の1地支（表の第3列）。 */
const YUESHA_BY_TRIO: readonly string[] = ["丑", "戌", "未", "辰"];

/** ［区分A］月刑（p.24）。月建ごとの固定1地支。 */
const YUEXING: Record<string, string> = {
  寅: "巳", 卯: "子", 辰: "辰", 巳: "申", 午: "午", 未: "丑",
  申: "寅", 酉: "酉", 戌: "未", 亥: "亥", 子: "卯", 丑: "戌",
};

/**
 * 「日家凶神」第2グループ（月破・劫殺・災殺・月殺・月刑）を判定する。
 * 吉神は今回対象外のため kichijin は常に空配列。
 */
export function resolveKyoushinGroup2(input: ShinsatsuInput): ShinsatsuResult {
  const { monthBranch, dayBranch } = input;
  const trio = trioIndexOf(monthBranch);

  const kyojin: string[] = [];
  if (YUEPO[monthBranch] === dayBranch) kyojin.push("月破");
  if (trio !== -1) {
    if (JIESHA_BY_TRIO[trio] === dayBranch) kyojin.push("劫殺");
    if (ZAISHA_BY_TRIO[trio] === dayBranch) kyojin.push("災殺");
    if (YUESHA_BY_TRIO[trio] === dayBranch) kyojin.push("月殺");
  }
  if (YUEXING[monthBranch] === dayBranch) kyojin.push("月刑");

  return { kichijin: [], kyojin };
}
