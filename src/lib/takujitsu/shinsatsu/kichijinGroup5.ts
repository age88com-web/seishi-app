/**
 * 「Ⅰ 神殺の原理　日家吉神」のうち、第1〜第4グループ未実装だった
 * 残りの吉神をまとめて判定する。凶神は今回未実装のため kyojin は
 * 常に空配列。
 */
export function resolveKichijinGroup5(input: ShinsatsuInput): ShinsatsuResult {
  const { monthBranch, dayStem, dayBranch } = input;
  const dayGanzhi = `${dayStem}${dayBranch}`;

  const kichijin: string[] = [];

  if (BUJIANG[monthBranch]?.includes(dayGanzhi)) kichijin.push("不將");

  // 十二建除（jianchu.ts、既存実装をそのまま呼び出すだけ。再実装しない）
  const jianchuName = resolveJianchu({ monthBranch, dayBranch }).name;
  if (jianchuName === "除") kichijin.push("吉期");
  if (jianchuName === "満") {
    kichijin.push("天巫");
    kichijin.push("福徳");
  }
  if (jianchuName === "定") kichijin.push("時陰");
  if (jianchuName === "執") kichijin.push("枝德");
  if (jianchuName === "成") {
    kichijin.push("天醫");
    kichijin.push("天喜");
  }
  if (jianchuName === "開") {
    kichijin.push("生氣");
    kichijin.push("時陽");
  }

  if (BINGJI[monthBranch]?.includes(dayBranch)) kichijin.push("兵吉");
  if (SHENZAI_GANZHI.includes(dayGanzhi)) kichijin.push("神在");
  if (DAMING_GANZHI.includes(dayGanzhi)) kichijin.push("大明");
  if (QISHENG_GANZHI.includes(dayGanzhi)) kichijin.push("七聖");

  return { kichijin, kyojin: [] };
}
