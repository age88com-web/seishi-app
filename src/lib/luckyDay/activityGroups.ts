/** activityId から表示グループを得る。未登録id（無いはず）は「その他・特殊用途」。 */
export function getActivityGroup(activityId: string): LuckyDayActivityGroup {
  return ACTIVITY_GROUP_BY_ID[activityId] ?? "その他・特殊用途";
}

// 開発時の自己検証（実行時コストは軽微・109件のみ）。
// 1 activityId → 1 group が全件で成立し、合計が ACTIVITY_DEFINITIONS と
// 一致することをモジュール読み込み時に確認する。判定ロジックには影響しない。
if (process.env.NODE_ENV !== "production") {
  const total = ACTIVITY_DEFINITIONS.length;
  const covered = ACTIVITY_DEFINITIONS.filter((d) => Boolean(ACTIVITY_GROUP_BY_ID[d.id])).length;
  if (covered !== total) {
    // eslint-disable-next-line no-console
    console.warn(
      `[luckyDay/activityGroups] ACTIVITY_GROUP_BY_ID の被覆件数(${covered})が` +
        `ACTIVITY_DEFINITIONS件数(${total})と一致していません。`,
    );
  }
}
