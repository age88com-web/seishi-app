// src/lib/luckyDay/activityGroups.ts
//
// 役割:
//   一般向け擇日サービス（/lucky-day）の「109活動すべて見る」表示専用の
//   用途グループ分類（ユーザー指示、2026-09-19）。
//
//   重要: これは表示の整理だけであり、good/neutral/mixed/badの判定
//   （evaluateActivities()）には一切関与しない。activityDefinitions.ts の
//   canonicalName・原典データ、既存の専門家向けカテゴリー
//   （src/lib/takujitsu/activity/activityCategories.ts）も変更していない。
//
// 生成方法（既存データを可能な限り再利用、ユーザー指示）:
//   ACTIVITY_DEFINITIONS 全109件について、以下の優先順位で12グループへ
//   1件ずつ割り当てた（1 activityId → 1 display group、重複・欠落なし）。
//     1) src/lib/luckyDay/purposeMapping.ts に既にユーザー承認済みの
//        具体的目的マッピングがあれば、そのカテゴリー項目
//        （src/lib/luckyDay/categories.ts）が属する大カテゴリーから
//        グループを決定する（例: "housing-move" 配下の用事→「住まい・建築」）。
//        同じactivityIdが複数のカテゴリー項目に登場する場合
//        （動土・修造動土・伐木・交易・立券交易・上官赴任。意図的な重複）は
//        categories.ts の並び順で最初に出現した項目を採用する。
//     2) purposeMapping.ts に無い活動は、既存の専門家向け15分類
//        （activityCategories.ts の categoryOf()）から下記の対応表で
//        12グループへ畳み込んだ。
//   例外2件のみ手動で上書きした（新しい意味判断ではなく、生成結果の
//   明らかな不整合を補正するもの）:
//     ・鋳造／造船 → 15分類では「就職・仕事」「その他」だが、内容が
//       金属鋳造・造船という製造行為そのものであるため「倉庫・設備・製造」。
//     ・祭祀 → purposeMapping.ts では「開業・開店に伴う祭祀を行う」
//       （work-open→仕事・お金）にも登場するが、祭祀そのものの主たる
//       意味（祖先・神仏への祈願儀礼）を優先し「祈願・神仏」とした。
//   検証（生成時に確認済み）: 全109件が重複・欠落なく12グループに
//   分割され、合計が109件と一致する。

