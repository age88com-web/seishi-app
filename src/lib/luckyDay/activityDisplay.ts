/** activityId から一般向け表示名を得る。 */
export function getLuckyDayActivityLabel(activityId: string): string {
  const override = LUCKY_DAY_LABEL_OVERRIDES[activityId];
  if (override) return override;
  const def = ACTIVITY_BY_ID[activityId];
  if (!def) return activityId;
  return def.modernLabel ?? def.modernName ?? def.canonicalName;
}

