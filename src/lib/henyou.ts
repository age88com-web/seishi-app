function stemGroupKey(stem: YearStem){
  if(stem==="甲"||stem==="己")return"甲、己";
  if(stem==="乙"||stem==="庚")return"乙、庚";
  if(stem==="丙"||stem==="辛")return"丙、辛";
  if(stem==="丁"||stem==="壬")return"丁、壬";
  return"戊、癸";
}

// 取得関数

export function getHenyou2ByYearBranch(
  name:keyof typeof HENYOU2_YEAR_BRANCH_TABLE,
  yearBranch:YearBranch
){
  return HENYOU2_YEAR_BRANCH_TABLE[name]?.[yearBranch] ?? null;
}

export function getHenyou2ByStemAndMing(
  name:any,
  stem:YearStem,
  ming:MingBranch
){
  const table=(HENYOU2_BY_NAME_AND_YEAR_MING as any)[name];
  if(!table)return null;

  if(table["全ての干"]) return table["全ての干"][ming] ?? null;

  const key=stemGroupKey(stem);
  return table[key]?.[ming] ?? table[stem]?.[ming] ?? null;
}

// bodies から「この星はどの記号か」を推定
export function guessHenyouMarkFromBody(b: any): HenyouMark | null {
  const id = String(b?.id ?? "");
  const key = String(b?.key ?? "");
  const label = String(b?.label ?? "");

  const s = (id + "|" + key + "|" + label).toLowerCase();

  if (s.includes("sun") || label.includes("太陽") || label === "日") return "日";
  if (s.includes("moon") || label.includes("太陰") || label === "月") return "月";
  if (s.includes("jupiter") || label.includes("木星")) return "木";
  if (s.includes("mars") || label.includes("火星")) return "火";
  if (s.includes("saturn") || label.includes("土星")) return "土";
  if (s.includes("venus") || label.includes("金星")) return "金";
  if (s.includes("mercury") || label.includes("水星")) return "水";
  if (s.includes("ziqi") || s.includes("purple") || label.includes("紫気")) return "気";
  if (s.includes("yuebo") || s.includes("bo") || label.includes("月孛")) return "孛";
  if (s.includes("rahu") || label.includes("羅喉")) return "羅";
  if (s.includes("ketu") || label.includes("計都")) return "計";

  return null;
}

// 既存変曜星アイテムを「宮（branch）」別に作る（表示文字列は「天○(星名)」）
export function buildHenyouByPalace(
  stem: YearStem,
  bodies: Array<{ id?: string; key?: string; label?: string; lonDeg: number }>,
  branchesB: readonly string[]
): Record<string, string[]> {
  const inv = invertHenyouForStem(stem);
  const out: Record<string, string[]> = {};

  const norm360 = (x: number) => ((x % 360) + 360) % 360;

  for (let i = 0; i < bodies.length; i++) {
    const b = bodies[i];
    const mark = guessHenyouMarkFromBody(b);
    if (!mark) continue;

    const tian = inv[mark];
    if (!tian) continue;

    const lon = norm360(b.lonDeg);
    const idx = Math.floor(lon / 30) % 12;
    const br = branchesB[idx];

    const starLabel = HENYOU_MARK_TO_LABEL[mark];
    const txt = `${tian}(${starLabel})`;

    if (!out[br]) out[br] = [];
    out[br].push(txt);
  }

  return out;
}