// ---------------------------------------------------------------------------
// 十二支の番号（子=0 … 亥=11。§0.4）
// ---------------------------------------------------------------------------

export function branchIndex(b: Branch): number {
  return BRANCHES.indexOf(b);
}

/** 番号（負や12以上も可）を十二支に戻す。 */
export function branchAt(i: number): Branch {
  return BRANCHES[((i % 12) + 12) % 12];
}

export function stemIndex(s: Stem): number {
  return STEMS.indexOf(s);
}

