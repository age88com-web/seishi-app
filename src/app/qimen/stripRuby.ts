// src/app/qimen/stripRuby.ts
//
// 剋應本文の「ルビ（ふりがな）」を表示時のみ取り除くユーティリティ。
//
//   剋應.pdf 由来の本文では、ふりがなが「かな＋空白だけで構成された 1 行」として
//   漢字の直前・直後の行に挿入されている（PDF のレイアウトを行テキストへ落とした痕跡）。
//
//     例）
//       己に壬を加えるとい
//             ちもうこうちょう          ← この行がルビ
//       うことです。地網高張 と呼ばれます。
//
//   実務用の印刷・画面表示ではこのルビ行が不要なため、
//   「かな（ひらがな／カタカナ）＋空白のみ」の行を丸ごと削除する。
//
//   - 本文・漢字・句読点・意味の注記（例:「（悪賢い子供）」）は一切変更しない。
//   - かなを含まない空行はそのまま残す（既存の改行を維持）。
//   - 元データ（JSON）は変更しない。表示直前にこの関数を通すだけ。

// ひらがな・カタカナ（濁点/半濁点・長音符・くり返し記号・半角カナ含む）
const KANA_CLASS = "\\u3040-\\u30FF\\u31F0-\\u31FF\\uFF66-\\uFF9F\\u3005";

// 行全体が「かな＋空白」だけで構成されているか
const KANA_ONLY_LINE = new RegExp(`^[\\s${KANA_CLASS}]+$`);
// その行が実際にかなを 1 文字以上含むか（純粋な空行を誤って消さないため）
const HAS_KANA = new RegExp(`[${KANA_CLASS}]`);

/**
 * 剋應本文からルビ行（かな＋空白のみの行）を除去する。
 * 改行位置はそのまま（ルビ行を丸ごと除くだけ。前後の本文行は結合しない）。
 */
export function stripRuby(text: string): string {
  if (!text) return text;
  return text
    .split("\n")
    .filter((line) => !(HAS_KANA.test(line) && KANA_ONLY_LINE.test(line)))
    .join("\n");
}
